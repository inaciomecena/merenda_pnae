// Rebuild the editable source texts from the extraction of the PDFs in docs/dre.
const fs = require('node:fs');
const path = require('node:path');
const raw = require('../../../docs/dre/textos-extraidos.json');
function clean(s) {
  return s.replace(/-- \d+ of \d+ --/g, '').replace(/^\d+\s*$/gm, '').replace(/\n{3,}/g, '\n\n').trim();
}
function html(s) {
  return s.split(/\n\s*\n/).map(p => '<p>' + p.trim().replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/\n/g, ' ') + '</p>').join('\n');
}
let principal = clean(raw['01_Edital_Principal.pdf']);
const start = principal.indexOf('Nº PRODUTO COM');
// The example's product prices and quantities belong to the previous call, not the template.
const end = principal.search(/\n2\.\s+(?:DA |DOS |DAS |HABILITA|FONTE)/);
if (start < 0 || end < start) throw new Error('Não foi possível identificar a tabela de itens do edital.');
principal = principal.slice(0, start) + '\n\n{{itens}}\n\n' + principal.slice(end);
principal = principal
  .replace(/001\/2025/g, '{{edital.numero}}/{{edital.ano}}')
  .replace(/170376\/2025/g, '{{edital.processoAdministrativo}}')
  .replace(/14 de janeiro de 2026/g, '{{edital.dataSessao}}')
  .replace(/09h:00min/g, '{{edital.horarioSessao}}')
  .replace(/Escola\s+Estadual Dr\. Arnaldo Estevão De Figueiredo, situada à Avenida Major Simão Aureliano De Barros, 229\s+CENTRO, Alto Paraguai - MT/g, '{{edital.localSessao}}')
  .replace(/dmt\.coadm@edu\.mt\.gov\.br/g, '{{entidade.email}}')
  .replace(/www\.drediamantino\.com\.br/g, '{{entidade.portal}}')
  .replace(/Diamantino, 26 de novembro de 2025\./g, '{{edital.municipio.nome}}, {{edital.dataPublicacao}}.')
  .replace(/Diamantino-MT/g, '{{edital.municipio.nome}}/{{edital.municipio.uf}}')
  .replace(/Alto Paraguai(?:\s*[-/]\s*MT)?/g, '{{edital.municipio.nome}}')
  .replace(/no ano letivo de 2026/g, 'no ano letivo de {{edital.ano}}');
let contrato = clean(raw['08_Anexo_VII_Minuta_Contrato.pdf']);
// Replace the preamble and empty product grid with named variables, retaining all clauses.
const clauses = contrato.indexOf('CLÁUSULA PRIMEIRA');
contrato = `ANEXO VII – Minuta de Contrato\n\nTERMO DE CONTRATO Nº {{contrato.numero}}\nProcesso administrativo nº {{edital.processoAdministrativo}}\nChamada pública nº {{edital.numero}}/{{edital.ano}}\n\nO CONSELHO DELIBERATIVO DA COMUNIDADE ESCOLAR – CDCE DA {{entidade.nome}}, CNPJ {{entidade.cnpj}}, com sede em {{entidade.endereco}}, {{entidade.municipio}}, representado por {{entidade.representante.nome}}, CPF {{entidade.representante.cpf}}, doravante CONTRATANTE, e {{produtor.nome}}, CPF/CNPJ {{produtor.cpfCnpj}}, com sede em {{produtor.endereco}}, {{produtor.municipio}}, representado por {{representante.nome}}, CPF {{representante.cpf}}, RG {{representante.rg}}/{{representante.orgaoRg}}, e-mail {{produtor.email}}, telefone {{produtor.telefone}}, doravante CONTRATADA, resolvem celebrar o presente contrato mediante as cláusulas que seguem:\n\n` + contrato.slice(clauses);
contrato = contrato.replace(/1\.2 Objeto da contratação:[\s\S]*?(?=1\.3 São anexos)/, '1.2 Objeto da contratação:\n\n{{itens}}\n\nValor Total do Contrato: {{projeto.valorTotal}}\n\n')
  .replace(/(?:nº|n\.)\s*\.{3,},?\s*de\s*[.\/\d\s]*202[.\/\s]*[,;]?/g, 'nº {{edital.numero}}/{{edital.ano}} ')
  .replace(/R\$\.{3,}\s*\(\.{3,}\)/g, '{{projeto.valorTotal}}')
  .replace(/Banco\s*\.{3,}\s*Agência nº\s*\.{3,},\s*conta corrente nº\s*\.{3,}\s*e pix\s*\.{3,}/g, 'Banco {{produtor.banco}}, Agência {{produtor.agencia}}, conta corrente {{produtor.conta}}, PIX {{produtor.pix}}')
  .replace(/Foro da Seção Judiciária\s*\.{3,}-\s*\.{3,}/g, 'Foro de {{edital.foro}}')
  .replace(/\[\.\.\.\] - MT, xx de xxxxxxx de 202x\./g, '{{projeto.local}}, {{projeto.data}}.')
  .replace(/Representante Legal: \[\.\.\.\]/g, 'Representante Legal: {{representante.nome}}')
  .replace(/\(NOME COMPLETO CPF OU CNPJ\)/g, '{{produtor.nome}} — {{produtor.cpfCnpj}}')
  .replace(/\(NOME COMPLETO CPF E CARGO\)/g, '{{entidade.representante.nome}} — {{entidade.representante.cpf}}');
const out = path.resolve(__dirname, '../src/modules/composicao-editais/application/domain/textos-dre-extraidos.ts');
const source = (name, text) => `export const ${name} = [\n${html(text).split('\n').map(p => '  ' + JSON.stringify(p) + ',').join('\n')}\n].join('\\n');\n`;
fs.writeFileSync(out, '// Generated by scripts/build-dre-texts.cjs from the user-provided PDFs.\n' + source('EDITAL_DRE', principal) + source('CONTRATO_DRE', contrato));
console.log('Textos do edital e contrato reconstruídos.');
