CREATE TABLE IF NOT EXISTS `pnae_audit_logs` (
  `id` VARCHAR(191) NOT NULL,
  `userId` VARCHAR(191) NULL,
  `userName` VARCHAR(191) NULL,
  `userEmail` VARCHAR(191) NULL,
  `userRole` VARCHAR(191) NULL,
  `action` VARCHAR(191) NOT NULL,
  `entity` VARCHAR(191) NOT NULL,
  `entityId` VARCHAR(191) NULL,
  `entityLabel` VARCHAR(191) NULL,
  `oldValues` TEXT NULL,
  `newValues` TEXT NULL,
  `ipAddress` VARCHAR(191) NULL,
  `userAgent` VARCHAR(191) NULL,
  `endpoint` VARCHAR(191) NULL,
  `method` VARCHAR(191) NULL,
  `statusCode` INTEGER NULL,
  `durationMs` INTEGER NULL,
  `metadata` TEXT NULL,
  `createdAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  INDEX `pnae_audit_logs_userId_idx` (`userId`),
  INDEX `pnae_audit_logs_action_idx` (`action`),
  INDEX `pnae_audit_logs_entity_idx` (`entity`),
  INDEX `pnae_audit_logs_createdAt_idx` (`createdAt`),
  PRIMARY KEY (`id`)
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
