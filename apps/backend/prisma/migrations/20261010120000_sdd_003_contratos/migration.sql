CREATE TABLE `pnae_contratos` (
  `id` VARCHAR(191) NOT NULL,
  `numero` VARCHAR(191) NOT NULL,
  `exercicio` INTEGER NOT NULL,
  `editalId` VARCHAR(191) NOT NULL,
  `chamadaPublica` VARCHAR(191) NULL,
  `propostaId` VARCHAR(191) NOT NULL,
  `produtorId` VARCHAR(191) NOT NULL,
  `escolaId` VARCHAR(191) NULL,
  `dreId` VARCHAR(191) NULL,
  `municipioId` VARCHAR(191) NULL,
  `valorInicial` DECIMAL(14, 2) NOT NULL,
  `valorAtualizado` DECIMAL(14, 2) NOT NULL,
  `dataAssinatura` DATETIME(3) NULL,
  `vigenciaInicio` DATETIME(3) NULL,
  `vigenciaFim` DATETIME(3) NULL,
  `status` ENUM('RASCUNHO', 'EM_CONFERENCIA', 'AGUARDANDO_ASSINATURA', 'VIGENTE', 'SUSPENSO', 'ENCERRADO', 'RESCINDIDO', 'CANCELADO') NOT NULL DEFAULT 'RASCUNHO',
  `objeto` TEXT NULL,
  `observacoes` TEXT NULL,
  `condicoesFornecimento` TEXT NULL,
  `condicoesPagamento` TEXT NULL,
  `fiscalizacao` TEXT NULL,
  `instrumentoExternoRegistrado` BOOLEAN NOT NULL DEFAULT false,
  `instrumentoRegistradoEm` DATETIME(3) NULL,
  `versao` INTEGER NOT NULL DEFAULT 1,
  `createdAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `updatedAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `deletedAt` DATETIME(3) NULL,
  `createdBy` VARCHAR(191) NULL,
  `updatedBy` VARCHAR(191) NULL,
  PRIMARY KEY (`id`),
  UNIQUE INDEX `pnae_contratos_numero_exercicio_key`(`numero`, `exercicio`),
  INDEX `pnae_contratos_status_idx`(`status`),
  INDEX `pnae_contratos_editalId_idx`(`editalId`),
  INDEX `pnae_contratos_propostaId_idx`(`propostaId`),
  INDEX `pnae_contratos_produtorId_idx`(`produtorId`),
  INDEX `pnae_contratos_dreId_idx`(`dreId`),
  INDEX `pnae_contratos_escolaId_idx`(`escolaId`),
  INDEX `pnae_contratos_municipioId_idx`(`municipioId`),
  INDEX `pnae_contratos_vigenciaFim_idx`(`vigenciaFim`),
  CONSTRAINT `pnae_contratos_editalId_fkey` FOREIGN KEY (`editalId`) REFERENCES `pnae_editais`(`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `pnae_contratos_propostaId_fkey` FOREIGN KEY (`propostaId`) REFERENCES `pnae_propostas`(`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `pnae_contratos_produtorId_fkey` FOREIGN KEY (`produtorId`) REFERENCES `produtores`(`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `pnae_contratos_escolaId_fkey` FOREIGN KEY (`escolaId`) REFERENCES `escolas`(`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `pnae_contratos_dreId_fkey` FOREIGN KEY (`dreId`) REFERENCES `dres`(`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `pnae_contratos_municipioId_fkey` FOREIGN KEY (`municipioId`) REFERENCES `municipios`(`id`) ON DELETE RESTRICT ON UPDATE CASCADE
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

